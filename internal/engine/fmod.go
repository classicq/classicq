const CHECKEDFILESCOUNT = len(CheckedFiles)

var fmod_warn_time float32

func FMod_CheckModel(name string, buf []byte, len_ int) {
	var modified bool

	i := 0
	for ; i < CHECKEDFILESCOUNT; i++ {
		if Q_strcasecmp(name, CheckedFiles[i].name) == 0 {
			break
		}
	}
	if i == CHECKEDFILESCOUNT {
		return
	}

	out := md5.Sum(buf[:len_])

	// the same name can be listed with more than one accepted sum
	for j := i; j < CHECKEDFILESCOUNT && Q_strcasecmp(name, CheckedFiles[j].name) == 0; j++ {
		modified = out != CheckedFiles[j].md5sum
		if !modified {
			break
		}
	}

	if CheckedFiles[i].checked && !CheckedFiles[i].modified && modified {
		if fmod_warn_time == 0 || cls.realtime-float64(fmod_warn_time) >= 3 {
			Cbuf_AddText("say warning: models changed !!  Use f_modified again\n")
			fmod_warn_time = float32(cls.realtime)
		}
	}
	CheckedFiles[i].modified = modified
	CheckedFiles[i].checked = true
}

func FMod_CvarInit() {
	Cmd_AddCommand("f_modified", FMod_Response)
}

func FMod_Response() {
	buf := "modified:"

	count := 0
	for i := 0; i < CHECKEDFILESCOUNT; i++ {
		if CheckedFiles[i].checked && CheckedFiles[i].modified {
			if len(buf) < 240 {
				buf += va(" %s", COM_SkipPath(CheckedFiles[i].name))
				count++
			} else {
				buf += " & more..."
				break
			}
		}
	}

	if count == 0 {
		buf = "all models ok"
	}

	verb := "say"
	if cls.state == ca_disconnected {
		verb = "echo"
	}
	Cbuf_AddText(va("%s %s\n", verb, buf))
}
